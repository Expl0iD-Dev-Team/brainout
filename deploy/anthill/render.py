"""Render the deployment-specific configuration for the anthill-dev stack.

Called by deploy.sh; reads its settings from the environment:

  ANTHILL_DIR      anthill-dev/dev directory (docker-compose.yml lives there)
  STATE_DIR        where generated files go (nginx.conf, service-rewrite.json)
  PUBLIC_HOST      address clients use (the server's public IP)
  TLS_PORT_OFFSET  public HTTPS port = service port + offset (default 10000)
  ROOT_PASSWORD    password of the Anthill dev:root account
  CONTROLLER_IMAGE, MARKET_IMAGE, NGINX_IMAGE, PORTS_FROM, PORTS_TO

Writes:
  $ANTHILL_DIR/docker-compose.override.yml
      every published port bound to 127.0.0.1 (only nginx faces the network),
      upstream build contexts dropped (they are not part of anthill-dev, the
      prebuilt images are used), the controller, the market service and nginx.
  $ANTHILL_DIR/discovery/discovery-services.json
      services the client uses get https://PUBLIC_HOST:<port+offset>; the rest
      stay on localhost.
  $STATE_DIR/nginx.conf
      TLS termination for those services.
  $STATE_DIR/service-rewrite.json
      public URL -> http://127.0.0.1:<port>, applied by run.sh, because the game
      master hands spawned game servers the public addresses and the server
      should not reach itself through NAT and TLS.

Standard library only (runs on a stock Ubuntu python3).
"""
import json
import os
import re
import sys

ANTHILL_DIR = os.environ["ANTHILL_DIR"]
STATE_DIR = os.environ["STATE_DIR"]
PUBLIC_HOST = os.environ["PUBLIC_HOST"]
OFFSET = int(os.environ.get("TLS_PORT_OFFSET", "10000"))
ROOT_PASSWORD = os.environ["ROOT_PASSWORD"]
CONTROLLER_IMAGE = os.environ["CONTROLLER_IMAGE"]
MARKET_IMAGE = os.environ["MARKET_IMAGE"]
NGINX_IMAGE = os.environ["NGINX_IMAGE"]
PORTS_FROM = os.environ["PORTS_FROM"]
PORTS_TO = os.environ["PORTS_TO"]

# Services the game client and its game servers talk to: the client's
# Constants.Connection.DISCOVER list plus environment and discovery themselves.
PUBLIC_SERVICES = {
    "login": 9501, "discovery": 9502, "environment": 9503, "event": 9506,
    "game": 9508, "leaderboard": 9510, "message": 9511, "profile": 9512,
    "promo": 9513, "social": 9514, "static": 9515, "store": 9516,
    "report": 9517, "blog": 9518, "market": 9519,
}
MARKET_PORT = PUBLIC_SERVICES["market"]
BROKER = "amqp://guest:guest@rabbitmq:5672/"


def public_url(port):
    return "https://%s:%d" % (PUBLIC_HOST, port + OFFSET)


def q(value):
    """YAML double-quoted scalar."""
    return json.dumps(str(value))


def parse_compose(path):
    """Services of the upstream compose file: name -> {"ports": [...], "build": str}.

    The file is plain block YAML with two-space service indentation, so a line
    scanner is enough and keeps this free of third-party YAML libraries.
    """
    services = {}
    current = None
    in_ports = False
    in_services = False
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if re.match(r"^services:\s*$", line):
            in_services = True
            continue
        if not in_services:
            continue
        m = re.match(r"^  ([A-Za-z0-9_-]+):\s*$", line)
        if m:
            current = services.setdefault(m.group(1), {"ports": [], "build": None})
            in_ports = False
            continue
        if current is None:
            continue
        m = re.match(r"^    ([a-z_]+):\s*(.*)$", line)
        if m:
            key, value = m.group(1), m.group(2).strip()
            in_ports = key == "ports"
            if key == "build":
                current["build"] = value
            continue
        if in_ports:
            m = re.match(r"^\s+-\s*\"?([0-9]+:[0-9]+(?:/(?:tcp|udp))?)\"?\s*$", line)
            if m:
                current["ports"].append(m.group(1))
            elif line.strip():
                in_ports = False
    return services


def render_override(services):
    out = ["# generated by deploy/anthill/deploy.sh (render.py) - do not edit by hand",
           "services:"]
    for name, svc in services.items():
        lines = []
        if svc["ports"]:
            lines.append("    ports: !override")
            lines += ["      - %s" % q("127.0.0.1:" + p) for p in svc["ports"]]
        # ../<service> contexts are not in anthill-dev; use the prebuilt images
        if svc["build"] and svc["build"].startswith(".."):
            lines.append("    build: !reset null")
        # Monitoring dashboards the game doesn't need; upstream's collectd image
        # doesn't even start (its start.sh isn't executable). Start them with
        # `docker compose --profile monitoring up -d` if wanted.
        if name in ("collectd", "grafana"):
            lines.append("    profiles: [\"monitoring\"]")
        if name == "anthill_login":
            lines += ["    environment:",
                      "      root_user_password: %s" % q(ROOT_PASSWORD)]
        if name == "anthill_game_controller":
            lines += ["    image: %s" % q(CONTROLLER_IMAGE),
                      "    environment:",
                      "      gs_host: %s" % q(PUBLIC_HOST),
                      "      ports_pool_from: %s" % PORTS_FROM,
                      "      ports_pool_to: %s" % PORTS_TO,
                      "      connection_password: %s" % q(ROOT_PASSWORD)]
        if lines:
            out.append("  %s:" % name)
            out += lines

    out += [
        "  anthill_market:",
        "    image: %s" % q(MARKET_IMAGE),
        "    container_name: anthill_market",
        "    ports:",
        "      - %s" % q("127.0.0.1:%d:%d" % (MARKET_PORT, MARKET_PORT)),
        "    volumes:",
        "      - ./keys/public:/keys",
        "    restart: always",
        "    environment:",
        "      host: %s" % q("http://anthill_market:%d" % MARKET_PORT),
        "      listen: %s" % q("port:%d" % MARKET_PORT),
        "      cache_host: redis",
        "      token_cache_host: redis",
        "      auth_key_public: /keys/anthill.pub",
        "      db_host: mysql",
        "      db_name: dev_market",
        "      db_username: anthill",
        "      db_password: Admin123",
        "      internal_broker: %s" % q(BROKER),
        "      internal_restrict: \"172.0.0.1/8\"",
        "      pubsub: %s" % q(BROKER),
        "      discovery_service: http://anthill_discovery:9502",
        "    depends_on:",
        "      - mysql",
        "      - redis",
        "      - rabbitmq",
        "  brainout_nginx:",
        "    image: %s" % q(NGINX_IMAGE),
        "    container_name: brainout_nginx",
        "    network_mode: host",
        "    restart: always",
        "    volumes:",
        "      - %s" % q(os.path.join(STATE_DIR, "nginx.conf") + ":/etc/nginx/nginx.conf:ro"),
        # only the server pair: the CA key stays out of the container
        "      - %s" % q(os.path.join(STATE_DIR, "tls", "server.crt") + ":/etc/nginx/tls/server.crt:ro"),
        "      - %s" % q(os.path.join(STATE_DIR, "tls", "server.key") + ":/etc/nginx/tls/server.key:ro"),
    ]
    return "\n".join(out) + "\n"


def render_nginx():
    servers = []
    for name, port in sorted(PUBLIC_SERVICES.items(), key=lambda kv: kv[1]):
        servers.append("""
    # %(name)s
    server {
        listen %(public)d ssl;
        location / {
            proxy_pass http://127.0.0.1:%(port)d;
        }
    }""" % {"name": name, "public": port + OFFSET, "port": port})

    return """# generated by deploy/anthill/deploy.sh (render.py) - do not edit by hand
worker_processes auto;
events { worker_connections 4096; }

http {
    access_log /dev/stdout;
    error_log /dev/stderr warn;
    server_tokens off;

    ssl_certificate /etc/nginx/tls/server.crt;
    ssl_certificate_key /etc/nginx/tls/server.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:SSL:10m;

    client_max_body_size 64m;

    # message and party sessions are websockets
    map $http_upgrade $connection_upgrade {
        default upgrade;
        '' close;
    }
    proxy_http_version 1.1;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $connection_upgrade;
    proxy_set_header Host $http_host;
    # Anthill treats requests from Docker networks (172.0.0.0/8) as internal.
    # nginx reaches the services through Docker's loopback proxy, so without the
    # real client address every outside request would pass that check.
    proxy_set_header X-Real-IP $remote_addr;
    proxy_read_timeout 3600s;
    proxy_send_timeout 3600s;
%s
}
""" % "\n".join(servers)


def render_discovery(path):
    data = json.load(open(path, encoding="utf-8"))
    svc = data["services"]
    svc["market"] = {
        "internal": "http://anthill_market:%d" % MARKET_PORT,
        "external": "",
        "broker": BROKER,
    }
    for name, entry in svc.items():
        ext = entry.get("external")
        if ext is None:
            continue
        if name in PUBLIC_SERVICES:
            entry["external"] = public_url(PUBLIC_SERVICES[name])
        else:
            m = re.search(r":(\d+)$", ext)
            if m:
                entry["external"] = "http://localhost:%s" % m.group(1)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=4)
    return sorted(svc)


def render_rewrite():
    return {public_url(port): "http://127.0.0.1:%d" % port for port in PUBLIC_SERVICES.values()}


def main():
    compose = os.path.join(ANTHILL_DIR, "docker-compose.yml")
    services = parse_compose(compose)
    for required in ("mysql", "anthill_login", "anthill_game_controller", "anthill_discovery"):
        if required not in services:
            sys.exit("render.py: %s not found in %s" % (required, compose))

    os.makedirs(STATE_DIR, exist_ok=True)
    with open(os.path.join(ANTHILL_DIR, "docker-compose.override.yml"), "w", encoding="utf-8") as f:
        f.write(render_override(services))
    with open(os.path.join(STATE_DIR, "nginx.conf"), "w", encoding="utf-8") as f:
        f.write(render_nginx())
    with open(os.path.join(STATE_DIR, "service-rewrite.json"), "w", encoding="utf-8") as f:
        json.dump(render_rewrite(), f, indent=2)
    names = render_discovery(os.path.join(ANTHILL_DIR, "discovery", "discovery-services.json"))

    published = sum(len(s["ports"]) for s in services.values())
    print("override: %d services, %d ports bound to 127.0.0.1" % (len(services), published))
    print("discovery services: " + ", ".join(names))
    print("public HTTPS ports: %d-%d" % (min(PUBLIC_SERVICES.values()) + OFFSET,
                                          max(PUBLIC_SERVICES.values()) + OFFSET))


if __name__ == "__main__":
    main()
